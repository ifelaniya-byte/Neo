class TaskComplexity(Enum):
    """Complexity levels for tasks."""
    TRIVIAL = "TRIVIAL"
    SIMPLE = "SIMPLE"
    MODERATE = "MODERATE"
    COMPLEX = "COMPLEX"
    EXPERT = "EXPERT"
    META = "META"  # Tasks that require meta-programming

class TaskDomain(Enum):
    """Domains for specialized tasks."""
    GENERAL = "GENERAL"
    COMPRESSION = "COMPRESSION"
    OPTIMIZATION = "OPTIMIZATION"
    RESEARCH = "RESEARCH"
    VALIDATION = "VALIDATION"
    SYSTEM = "SYSTEM"
    LEARNING = "LEARNING"

@dataclass
class GeneratedCode:
    """Code generated by the meta-programming system."""
    code_id: str
    code: str
    language: str
    complexity: TaskComplexity
    domain: TaskDomain
    description: str
    dependencies: List[str]
    estimated_execution_time: float
    success_probability: float
    safety_score: float
    
    def to_dict(self):
        return self.__dict__

@dataclass
class TaskSpecification:
    """Detailed specification for a task."""
    task_id: str
    task_name: str
    description: str
    complexity: TaskComplexity
    domain: TaskDomain
    requirements: List[str]
    constraints: List[str]
    expected_output: str
    timeout: int
    priority: int
    created_at: str
    
    def to_dict(self):
        return self.__dict__

class MetaProgrammingSystem:
    """
    System for meta-programming - generating code and instructions for clones.
    The micro-LLM can program clones to accomplish any task indefinitely.
    """
    
    def __init__(self):
        self.code_library = {}  # Library of generated code
        self.task_templates = {}  # Templates for common tasks
        self.code_performance = {}  # Track performance of generated code
        self.meta_patterns = {}  # Learn patterns in meta-programming
        self.safety_checks = SafetyChecker()
        self.code_generator = CodeGenerator()
        self.task_decomposer = TaskDecomposer()
        
    def generate_task_code(self, task_spec: TaskSpecification) -> GeneratedCode:
        """Generate code to accomplish a specific task."""
        # Check if we have a similar task in library
        similar_code = self.find_similar_code(task_spec)
        
        if similar_code:
            # Adapt existing code
            adapted_code = self.adapt_code(similar_code, task_spec)
            return adapted_code
        
        # Generate new code
        generated_code = self.code_generator.generate(task_spec)
        
        # Validate code
        if self.safety_checks.validate(generated_code):
            # Add to library
            self.add_to_code_library(generated_code)
            return generated_code
        else:
            # Code failed safety checks
            print(f"[META-PROGRAMMING] Generated code failed safety checks")
            return None
    
    def decompose_complex_task(self, task_spec: TaskSpecification) -> List[TaskSpecification]:
        """Decompose a complex task into simpler subtasks."""
        if task_spec.complexity in [TaskComplexity.TRIVIAL, TaskComplexity.SIMPLE]:
            return [task_spec]
        
        # Decompose task
        subtasks = self.task_decomposer.decompose(task_spec)
        
        return subtasks
    
    def assign_task_to_clone(self, task_spec: TaskSpecification, clone_capabilities: List[str]) -> Dict:
        """Assign a task to a clone with appropriate code."""
        # Generate code for the task
        generated_code = self.generate_task_code(task_spec)
        
        if not generated_code:
            return {'success': False, 'error': 'Code generation failed'}
        
        # Create task package
        task_package = {
            'task_spec': task_spec.to_dict(),
            'generated_code': generated_code.to_dict(),
            'execution_instructions': self.generate_execution_instructions(generated_code),
            'resource_requirements': self.estimate_resource_requirements(generated_code),
            'validation_criteria': self.generate_validation_criteria(task_spec)
        }
        
        return {'success': True, 'task_package': task_package}
    
    def generate_indefinite_task_loop(self, base_task: TaskSpecification) -> GeneratedCode:
        """Generate code for a task that runs indefinitely."""
        # Create a loop structure
        loop_code = self.code_generator.generate_indefinite_loop(base_task)
        
        return loop_code
    
    def find_similar_code(self, task_spec: TaskSpecification) -> Optional[GeneratedCode]:
        """Find similar code in the library."""
        for code_id, code in self.code_library.items():
            if (code.domain == task_spec.domain and 
                code.complexity == task_spec.complexity):
                # Check description similarity
                if self.similarity_check(code.description, task_spec.description):
                    return code
        
        return None
    
    def adapt_code(self, existing_code: GeneratedCode, new_task: TaskSpecification) -> GeneratedCode:
        """Adapt existing code for a new task."""
        # Modify the code to fit new requirements
        adapted_code_str = self.code_generator.adapt(existing_code.code, new_task)
        
        return GeneratedCode(
            code_id=self.generate_code_id(),
            code=adapted_code_str,
            language=existing_code.language,
            complexity=new_task.complexity,
            domain=new_task.domain,
            description=new_task.description,
            dependencies=existing_code.dependencies,
            estimated_execution_time=existing_code.estimated_execution_time,
            success_probability=existing_code.success_probability * 0.9,  # Slightly lower for adapted code
            safety_score=existing_code.safety_score
        )
    
    def add_to_code_library(self, code: GeneratedCode):
        """Add generated code to the library."""
        self.code_library[code.code_id] = code
    
    def generate_execution_instructions(self, code: GeneratedCode) -> str:
        """Generate execution instructions for the code."""
        instructions = f"""
# Execution Instructions for {code.code_id}

## Overview
{code.description}

## Complexity
{code.complexity.value}

## Domain
{code.domain.value}

## Dependencies
{', '.join(code.dependencies) if code.dependencies else 'None'}

## Estimated Execution Time
{code.estimated_execution_time:.2f} seconds

## Success Probability
{code.success_probability:.2f}

## Safety Score
{code.safety_score:.2f}

## Execution Steps
1. Load dependencies
2. Initialize environment
3. Execute main code block
4. Validate output
5. Handle errors appropriately
6. Report results

## Error Handling
- Monitor for exceptions
- Log all errors
- Implement fallback strategies
- Report failure conditions
"""
        return instructions
    
    def estimate_resource_requirements(self, code: GeneratedCode) -> Dict:
        """Estimate resource requirements for code execution."""
        base_memory = 100  # MB
        base_cpu = 0.1  # 10% CPU
        
        # Adjust based on complexity
        complexity_multiplier = {
            TaskComplexity.TRIVIAL: 1.0,
            TaskComplexity.SIMPLE: 1.5,
            TaskComplexity.MODERATE: 2.0,
            TaskComplexity.COMPLEX: 3.0,
            TaskComplexity.EXPERT: 5.0,
            TaskComplexity.META: 10.0
        }
        
        multiplier = complexity_multiplier.get(code.complexity, 2.0)
        
        return {
            'memory_mb': int(base_memory * multiplier),
            'cpu_percent': base_cpu * multiplier,
            'estimated_duration': code.estimated_execution_time,
            'max_concurrent_instances': int(10 / multiplier)
        }
    
    def generate_validation_criteria(self, task_spec: TaskSpecification) -> List[str]:
        """Generate validation criteria for task completion."""
        criteria = [
            "Task completed without exceptions",
            "Output matches expected format",
            "Execution time within acceptable limits",
            "Resource usage within expected bounds"
        ]
        
        # Add domain-specific criteria
        if task_spec.domain == TaskDomain.COMPRESSION:
            criteria.extend([
                "Compression ratio achieved",
                "Data integrity maintained",
                "Decompression successful"
            ])
        elif task_spec.domain == TaskDomain.OPTIMIZATION:
            criteria.extend([
                "Performance improvement achieved",
                "No regression in other metrics",
                "Stability maintained"
            ])
        
        return criteria
    
    def similarity_check(self, description1: str, description2: str) -> bool:
        """Check similarity between two descriptions."""
        # Simple keyword overlap check
        words1 = set(description1.lower().split())
        words2 = set(description2.lower().split())
        
        overlap = len(words1 & words2)
        total = len(words1 | words2)
        
        similarity = overlap / total if total > 0 else 0
        
        return similarity > 0.3  # 30% similarity threshold
    
    def generate_code_id(self) -> str:
        """Generate unique code ID."""
        timestamp = str(int(time.time()))
        random_suffix = hashlib.md5(str(time.time()).encode()).hexdigest()[:8]
        return f"code_{timestamp}_{random_suffix}"
    
    def get_code_library_stats(self) -> Dict:
        """Get statistics about the code library."""
        if not self.code_library:
            return {}
        
        by_domain = {}
        by_complexity = {}
        
        for code in self.code_library.values():
            domain = code.domain.value
            complexity = code.complexity.value
            
            by_domain[domain] = by_domain.get(domain, 0) + 1
            by_complexity[complexity] = by_complexity.get(complexity, 0) + 1
        
        return {
            'total_code_items': len(self.code_library),
            'by_domain': by_domain,
            'by_complexity': by_complexity,
            'avg_success_probability': sum(c.success_probability for c in self.code_library.values()) / len(self.code_library),
            'avg_safety_score': sum(c.safety_score for c in self.code_library.values()) / len(self.code_library)
        }

class SafetyChecker:
    """Validates generated code for safety and correctness."""
    
    def __init__(self):
        self.blocked_patterns = [
            'eval(',
            'exec(',
            '__import__',
            'open(',
            'subprocess.',
            'os.system',
            'socket.',
            'input('
        ]
        
    def validate(self, code: GeneratedCode) -> bool:
        """Validate generated code."""
        # Check for blocked patterns
        for pattern in self.blocked_patterns:
            if pattern in code.code:
                print(f"[SAFETY] Blocked pattern found: {pattern}")
                return False
        
        # Try to parse the code
        try:
            ast.parse(code.code)
        except SyntaxError as e:
            print(f"[SAFETY] Syntax error in generated code: {e}")
            return False
        
        # Check safety score
        if code.safety_score < 0.7:
            print(f"[SAFETY] Safety score too low: {code.safety_score}")
            return False
        
        return True

class CodeGenerator:
    """Generates code for specific tasks."""
    
    def generate(self, task_spec: TaskSpecification) -> GeneratedCode:
        """Generate code for a task specification."""
        # Select appropriate code template based on domain
        template = self.get_template(task_spec.domain)
        
        # Fill template with task-specific details
        code = self.fill_template(template, task_spec)
        
        return GeneratedCode(
            code_id=hashlib.md5(str(time.time()).encode()).hexdigest()[:12],
            code=code,
            language="python",
            complexity=task_spec.complexity,
            domain=task_spec.domain,
            description=task_spec.description,
            dependencies=self.extract_dependencies(code),
            estimated_execution_time=self.estimate_execution_time(task_spec),
            success_probability=self.estimate_success_probability(task_spec),
            safety_score=self.estimate_safety_score(code)
        )
    
    def generate_indefinite_loop(self, base_task: TaskSpecification) -> GeneratedCode:
        """Generate code for an indefinite task loop."""
        code_template = """
import time
import logging

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

def main():
    while True:
        try:
            # Task implementation
            {task_implementation}
            
            # Sleep to prevent CPU overload
            time.sleep({sleep_interval})
            
        except KeyboardInterrupt:
            logger.info("Task interrupted by user")
            break
        except Exception as e:
            logger.error(f"Error in task execution: {{e}}")
            # Continue execution despite errors

if __name__ == "__main__":
    main()
"""
        
        # Fill in task-specific implementation
        task_impl = self.generate_task_implementation(base_task)
        code = code_template.format(
            task_implementation=task_impl,
            sleep_interval=1.0
        )
        
        return GeneratedCode(
            code_id=hashlib.md5(str(time.time()).encode()).hexdigest()[:12],
            code=code,
            language="python",
            complexity=TaskComplexity.META,
            domain=base_task.domain,
            description=f"Indinite loop: {base_task.description}",
            dependencies=["time", "logging"],
            estimated_execution_time=float('inf'),  # Runs indefinitely
            success_probability=0.8,
            safety_score=0.9
        )
    
    def get_template(self, domain: TaskDomain) -> str:
        """Get code template for a domain."""
        templates = {
            TaskDomain.COMPRESSION: self.compression_template(),
            TaskDomain.OPTIMIZATION: self.optimization_template(),
            TaskDomain.RESEARCH: self.research_template(),
            TaskDomain.VALIDATION: self.validation_template(),
            TaskDomain.GENERAL: self.general_template()
        }
        
        return templates.get(domain, self.general_template())
    
